import Foundation

/// ライブラリ機能のメニュー項目の出し分け [フェーズ 2 の結線]。
///
/// **View の条件式ではなく値として持つ。** 実機検証で「無効化」を
/// オンライン条件で塞いでいた欠陥を踏んだ——**ボリュームを失うと
/// 二度と無効化できない**という、縮退状態でこそ困る形だった。
/// View に書いた条件はテストで固定できないので、判断だけを切り出す。
public enum LibraryMenuVisibility {
    /// - Parameters:
    ///   - isEnabled: この登録がライブラリとして有効か。
    ///   - isOnline: 根が `.online` か（`FolderTreeRowContext.allowsWriting`）。
    public static func items(isEnabled: Bool, isOnline: Bool) -> Set<Item> {
        guard isEnabled else {
            // 有効化は**オンラインを要る**——`resolvedPath`/`volumeUUID` を
            // 実測できないため [1-17]。登録ウィザード（登録＝ライブラリ化
            // [RG3-20]）以前の「登録済みだが未有効」の登録だけがここに来る。
            return isOnline ? [.enable] : []
        }
        // **有効なライブラリの右クリックは「設定」だけ**［ユーザー指示、
        // 19章 §19.6: 登録解除と設定以外は通常のフォルダと同じでよい］。
        // 以前並べていた項目の行き先:
        // - 再スキャン: 廃止。ファイルの変更（FSEvents）と設定の保存が
        //   自動で走査を起こすので、手で押す場面が無い [RG3-24][RG3-25]
        // - 無効化: 登録解除に一本化 [RG3-30]
        // - ラベル編集・保管庫・整理ウインドウ群: メニューからは外し、
        //   走査結果・通知履歴からの導線と各ウインドウ内の入口に任せる
        //   （機能そのものは残っている。メンテナンス統合は Stage 4 の対象）。
        //   ラベル編集はステージ 3 でフィールド見出し [RL3-04]・メニューバー
        //   「ライブラリ」に入口が付いた。
        // 設定はオンラインを要らない——DB の設定を書き換えるだけで、
        // **縮退状態でこそ触りたい**ことがある（登録し直す前に型を直す等）。
        return [.settings]
    }

    /// 出しうる項目。**Stage P の最小化以降、実際に返るのは `enable` と
    /// `settings` だけ**——旧項目の case はどこからも返らない死んだ値に
    /// なっていたので、行型の統合（§19.13-3、ステージ 3）と同時に削除した。
    /// Stage 4（メンテナンス統合）で入口を足すときは case を増やし、
    /// `RegisteredRootMenuItems`（唯一の消費側）に項目を書く。
    public enum Item: Hashable, Sendable {
        case enable, settings
    }
}

