import Foundation

/// **その場所がゴミ箱の中か**を、ファイルシステムに一切触れずに答える
/// [RG3-03][BM-2]。
///
/// ## なぜ必要か
/// ブックマークは inode を追跡するので、登録フォルダをゴミ箱へ移しても
/// **解決は成功し続ける**（8章 §8.7.1 BM-2）。判定しなければ、その登録は
/// 「正常」のままツリーに並び、ドロップ・新規フォルダ作成・展開といった
/// 書き込みまで通ってしまう——ユーザーがゴミ箱を空にした瞬間に消える場所へ、
/// 気づかないまま書き続けることになる。
///
/// ## なぜ Apple 推奨の API を使わないのか [実測]
/// `NSFileManager.h` は「ゴミ箱にあるか調べるにはこれ」として
/// `getRelationship(_:of: .trashDirectory, in: [], toItemAt:)` を名指しで
/// 挙げている。それでもこちらを採るのは、実測すると**判定したい場面でこそ
/// 失敗する**ためである。
///
/// | 被験体 | `getRelationship` | 本実装 |
/// |---|---|---|
/// | `~/.Trash/…` | contains | ゴミ箱 |
/// | `/Volumes/X/.Trashes/501/…` | contains | ゴミ箱 |
/// | 通常のフォルダ | other | 通常 |
/// | **`.Trashes` がまだ無いボリューム** | **失敗 `NSCocoaErrorDomain 3328`** | 通常 |
/// | **存在しないパス** | **失敗 `NSCocoaErrorDomain 3328`** | 通常 |
///
/// 3328 の真因は「そのボリュームがゴミ箱に対応していない」ではなく
/// **「そのボリュームにまだ `.Trashes` ディレクトリが存在せず、`create: false`
/// で尋ねた」**である［実測。同一マシンで、一度も何も捨てていない外付け
/// （`/Volumes/T7`）は失敗し、`.Trashes/501` が既にある外付け
/// （`/Volumes/PRO-G40`）は成功した］。
///
/// - Important: **`create: true` で回避しようとしないこと。** 「この場所は
///   ゴミ箱か」を尋ねただけで、対象ボリュームに `.Trashes` を作ってしまう。
///   [CL-01]（登録フォルダ配下をアプリ由来のファイルで汚さない）に正面から
///   反する。
///
/// 加えて、`.missing` の判定と併用できないという構造的な問題がある——
/// 存在しないパスでも 3328 なので、「ゴミ箱ではない」と「もう無い」を
/// このエラーからは区別できない。本実装は純粋な文字列処理なので**決して
/// 失敗せず**、I/O も伴わないため応答しないボリュームでも即座に答える
/// [NV6-02]。
///
/// ## 判定をわざと緩くしてある [設計判断]
/// 成分のどこかに `.Trash`／`.Trashes` があれば真とする。位置まで縛れば
/// （`~/.Trash` は実ホーム直下、`.Trashes` はボリューム直下、など）
/// ユーザーが自分で `.Trash` という名前のフォルダを作った場合の誤検出を
/// 減らせるが、**取り違えたときの害が非対称**なのでこの向きに倒している。
///
/// - 誤って「ゴミ箱」と言う: 警告を出して読み取り専用に落とすだけ。
///   登録は自動削除しない [RG3-04] ので、ユーザーはいつでも解除できる。
/// - 誤って「通常」と言う: **ゴミ箱の中へ書き込みを許してしまう。**
///   これがそもそも塞ぎたかった穴そのものである。
///
/// 将来 macOS がゴミ箱の置き場所を増やしても、名前さえ同じなら緩い側は
/// 追随できる。
public enum TrashLocation {

    /// ゴミ箱を構成するディレクトリ名 [実測]。
    ///
    /// - `.Trash`: 起動ボリューム。実体は `~/.Trash/<名前>`。
    /// - `.Trashes`: 起動ボリューム以外。実体は `/Volumes/<名前>/.Trashes/<uid>/<名前>`。
    ///
    /// サンドボックス下でも**実ホーム側の** `~/.Trash` が返ることを確認済み
    /// （コンテナ内の別の場所ではない）。実アプリと同じ entitlement で
    /// アドホック署名したプローブで、ゴミ箱へ移したあとも app-scoped
    /// ブックマークが解決でき、セキュリティスコープも開き、中身も読めた
    /// ——つまりこの判定に到達する経路は実際に成立する。
    static let directoryNames: Set<String> = [".Trash", ".Trashes"]

    /// `url` がゴミ箱の中にあるか。**I/O を伴わないのでどこから呼んでもよい。**
    public static func isInTrash(_ url: URL) -> Bool {
        contains(pathComponents: url.standardizedFileURL.pathComponents)
    }

    /// ``isInTrash(_:)`` のパス文字列版。解決済みの URL を持たない場面
    /// （最後に解決できたパスだけが手元にある等）で使う。
    public static func isInTrash(path: String) -> Bool {
        contains(pathComponents: (path as NSString).pathComponents)
    }

    /// **成分単位で照合する。** 素の文字列包含にすると `~/Documents/.Trashy`
    /// や `MyStuff/Trash Talk` まで拾ってしまう。
    private static func contains(pathComponents: [String]) -> Bool {
        pathComponents.contains { directoryNames.contains($0) }
    }
}
