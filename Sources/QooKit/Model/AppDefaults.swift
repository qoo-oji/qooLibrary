//
//  既定値の集約 [4章 命名規約: マジックナンバー直書き禁止]。
//
//  `AppLimits` が「これ以上は許さない」上限を持つのに対し、こちらは
//  「何も指定されなければこう振る舞う」既定値を持つ。
//
import Foundation

public enum AppDefaults {

    public enum Library {
        /// 新規ライブラリの対象拡張子 [要件定義書 11.4 節:
        /// 「対象拡張子は全テンプレート共通で `zip, cbz, rar, cbr, 7z, cb7,
        /// pdf, epub`」][AL-11][IF-01]。
        ///
        /// **空集合を既定にしてはならない。** `LibraryEnumerator` は空を
        /// 「拡張子で絞らない＝すべてのファイルが対象」と解釈するため、
        /// 空のまま登録すると `.DS_Store` やメモの `.txt` まで蔵書として
        /// 取り込む。ブックフォルダの判定 [IF-01] も「直下に対象拡張子
        /// ファイルが 0 件」を条件にするので、空だと画像フォルダが
        /// 1 冊と見なされなくなる——**空は「既定」ではなく別の意味を持つ**。
        public static let targetExtensions: Set<String> = [
            "zip", "cbz", "rar", "cbr", "7z", "cb7", "pdf", "epub",
        ]

        /// 新規ライブラリの保護文字列 [PT-01、2026-08 のユーザー要望]。
        ///
        /// **括弧に入った年号と完結の印は、区切りとして読まれると邪魔になる。**
        /// `作品名 (2019) 第01巻` の `2019` が巻数と誤読されたり、`(` `)` が
        /// フィールドの境界と見なされたりするのを防ぐ。**一致した部分は値として
        /// 残る**（取り除きはしない）——保護文字列は「1 かたまりとして読む」ための
        /// 仕組みで、削除の仕組みではない [PT-02]。
        ///
        /// 1900〜2099 に絞ってあるのは、`(1234)` のような 4 桁を巻き込まないため。
        public static let protectedTokenPatterns: [String] = [
            #"\((19[0-9]{2})\)"#,
            #"\((20[0-9]{2})\)"#,
            #"\((結|終|完|完結|完全版)\)"#,
        ]
    }

    public enum Duplicates {
        /// 「指定した形式を優先する」[DU-25] の既定の並び。**先頭ほど残す。**
        ///
        /// `cb*` を素の容器より先に置くのは、そちらが**マンガとして明示的に
        /// 印を付けられた**もので、同じ中身なら意図して付け直された側だから。
        /// `pdf` / `epub` を最後に置くのは、スキャン物では容器より再圧縮や
        /// 縮小を経ていることが多いため——**中身の優劣ではなく、由来の
        /// 推測**にすぎないので、比較ビューから並べ替えられるようにする。
        public static let formatPreference: [String] = [
            "cbz", "cb7", "cbr", "zip", "7z", "rar", "pdf", "epub",
        ]
    }
}
